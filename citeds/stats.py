"""Dataset statistics as a Markdown report (docs/dataset_stats.md)."""
from __future__ import annotations

import pandas as pd


def _dist(s: pd.Series) -> str:
    if s.empty:
        return "n/a"
    q = s.quantile([0.25, 0.5, 0.75, 0.9, 0.99])
    return (f"mean {s.mean():.2f}, median {q[0.5]:.0f}, p25 {q[0.25]:.0f}, p75 {q[0.75]:.0f}, "
            f"p90 {q[0.9]:.0f}, p99 {q[0.99]:.0f}, max {s.max():.0f}")


def _bucket(n: pd.Series) -> pd.Series:
    return pd.cut(n, bins=[-1, 0, 2, 10, 50, float("inf")],
                  labels=["0", "1-2", "3-10", "11-50", ">50"])


def compute_stats(papers: pd.DataFrame, contexts: pd.DataFrame, index_contexts: pd.DataFrame,
                  edges: pd.DataFrame, queries: pd.DataFrame, cleaning_log: dict) -> str:
    L = ["# Dataset statistics", "",
         "Generated by `python -m citeds.build`. Do not edit by hand.", "",
         "## Overview", "", "| Item | Count |", "|---|---:|"]
    rows = [
        ("Papers (documents)", len(papers)),
        ("Papers cited at least once", int((papers["citation_count"] > 0).sum())),
        ("Citation contexts (all, cleaned)", len(contexts)),
        ("Citation contexts in index (after leakage control)", len(index_contexts)),
        ("Contexts removed by leakage control", len(contexts) - len(index_contexts)),
        ("Distinct citing sentences", contexts["sentence_id"].nunique()),
        ("Citation edges", len(edges)),
        ("Queries (all splits)", len(queries)),
    ]
    for s, n in queries["split"].value_counts().reindex(["train", "val", "test"]).fillna(0).items():
        rows.append((f"Queries: {s}", int(n)))
    rows.append(("Distinct relevant papers across queries", queries["cited_paper_id"].nunique()))
    L += [f"| {k} | {v:,} |" for k, v in rows]

    L += ["", "## Distributions", "", "| Quantity | Distribution |", "|---|---|",
          f"| Citation count per paper (in-corpus) | {_dist(papers['citation_count'])} |",
          f"| Contexts per cited paper (index) | {_dist(index_contexts.groupby('cited_paper_id').size())} |",
          f"| Abstract length (tokens) | {_dist(papers['abstract'].str.split().str.len())} |",
          f"| Context length (tokens) | {_dist(contexts['text'].str.split().str.len())} |",
          f"| Query length (tokens) | {_dist(queries['text'].str.split().str.len())} |",
          f"| Papers cited per sentence | {_dist(contexts.drop_duplicates('sentence_id')['num_cited_in_sentence'])} |"]

    yr = papers["year"].dropna().astype(int)
    if not yr.empty:
        L += [f"| Publication year | {yr.min()}-{yr.max()}, median {int(yr.median())} |"]

    L += ["", "## Citation-count buckets (popularity / cold start)", "",
          "| In-corpus citations | Papers | Share of papers | Queries targeting these papers |",
          "|---|---:|---:|---:|"]
    pb = _bucket(papers["citation_count"]).value_counts().sort_index()
    qb = _bucket(queries["cited_citation_count"]).value_counts().sort_index()
    for b in pb.index:
        L.append(f"| {b} | {pb[b]:,} | {pb[b] / max(len(papers), 1):.1%} | {int(qb.get(b, 0)):,} |")

    L += ["", "## Most common sections of citation contexts", "", "| Section | Contexts |", "|---|---:|"]
    for sec, n in contexts["section"].replace("", "(none)").value_counts().head(10).items():
        L.append(f"| {sec} | {n:,} |")

    L += ["", "## Cleaning log", "", "| Step | Count |", "|---|---:|"]
    L += [f"| {k} | {v:,} |" for k, v in cleaning_log.items()]
    return "\n".join(L) + "\n"
